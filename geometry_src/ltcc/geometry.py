# ltccBox.pl — sector gas mother volume built from Trap/Box/Tube booleans
# ---------------------------------------------------------------------------
def build_ltcc_box(configuration, presence, gas):
    diff = 235
    p_dx1 = 240
    p_dx2 = 2000
    p_dz = 500
    p_dy = 1700
    p_dx3 = p_dx1 - diff
    p_dx4 = p_dx2 - diff

    trap = component_volume("ltccTrap")
    trap.description = "Light Threshold Cerenkov Counter"
    trap.color = "110088"
    trap.solid = "G4Trap"
    trap.parameters = (
        f"{p_dz}*mm, 0*deg, 0*deg, {p_dy}*mm, {p_dx1}*mm, {p_dx2}*mm, 0*deg, "
        f"{p_dy}*mm, {p_dx3}*mm, {p_dx4}*mm, 0*deg"
    )
    trap.publish(configuration)

    # Subtract box at 45ish degrees from the top
    y_upper = p_dy
    z_upper = p_dz
    box_x, box_y, box_z = 3000.0, 600.0, 3000.0
    box_angle = -20 * math.pi / 180.0
    absbox_angle = 20 * math.pi / 180.0
    y_box_p = y_upper - (box_z * math.sin(absbox_angle) - box_y * math.cos(absbox_angle))
    z_box_p = -z_upper + (box_z * math.cos(absbox_angle) + box_y * math.sin(absbox_angle))

    top_box = component_volume("ltccTopBox")
    top_box.description = "Box to subtract from LTCC"
    top_box.position = f"0*mm, {fstr(y_box_p)}*mm, {fstr(z_box_p)}*mm"
    top_box.rotations = [f"{fstr(box_angle)}*rad, 0*deg, 0*deg"]
    top_box.color = "110088"
    top_box.solid = "G4Box"
    top_box.parameters = f"{fstr(box_x)}*mm, {fstr(box_y)}*mm, {fstr(box_z)}*mm"
    top_box.publish(configuration)

    minus_top_box = component_volume("ltccMinusTopBox")
    minus_top_box.description = "Trap minus Top Box "
    minus_top_box.color = "110088"
    operation(minus_top_box, "ltccTrap - ltccTopBox").publish(configuration)

    # Subtract tube
    tube_hole = component_volume("ltccTubeHole")
    tube_hole.description = "Tube to subtract from LTCC "
    tube_hole.position = "0*mm, -600*mm, 3500*mm"
    tube_hole.rotations = ["0*deg, 90*deg, 0*deg"]
    tube_hole.color = "110088"
    tube_hole.solid = "G4Tubs"
    tube_hole.parameters = "0*mm, 3250*mm, 4500*mm, 0*deg, 360*deg"
    tube_hole.publish(configuration)

    trap_minus_hole = component_volume("ltccTrapMinusHole")
    trap_minus_hole.description = "Trap minus Top Box minus Tube"
    trap_minus_hole.color = "110088"
    operation(trap_minus_hole, "ltccMinusTopBox - ltccTubeHole").publish(configuration)

    # Subtract box at 25ish degrees from the bottom
    y_upper = -p_dy - 100
    z_upper = p_dz
    box_x, box_y, box_z = 3000.0, 800.0, 3000.0
    box_angle = 25 * math.pi / 180.0
    absbox_angle = 25 * math.pi / 180.0
    y_box_p = y_upper + (box_z * math.sin(absbox_angle) - box_y * math.cos(absbox_angle))
    z_box_p = -z_upper + (box_z * math.cos(absbox_angle) + box_y * math.sin(absbox_angle))

    bottom_box = component_volume("ltccBottomBox")
    bottom_box.description = "Box to subtract from LTCC"
    bottom_box.position = f"0*mm, {fstr(y_box_p)}*mm, {fstr(z_box_p)}*mm"
    bottom_box.rotations = [f"{fstr(box_angle)}*rad, 0*deg, 0*deg"]
    bottom_box.color = "110088"
    bottom_box.solid = "G4Box"
    bottom_box.parameters = f"{fstr(box_x)}*mm, {fstr(box_y)}*mm, {fstr(box_z)}*mm"
    bottom_box.publish(configuration)

    # Trap - Box - Tube - Box 2: these numbers are empirical to match
    # by eyes the box to the mirror position
    trap_box = component_volume("trapBox")
    trap_box.description = "Trap minus Top Box minus Tube minus Bottom Box"
    trap_box.position = "0*mm, 1800*mm, 3900*mm"
    trap_box.rotations = ["25*deg, 180*deg, 0*deg"]
    trap_box.color = "110088"
    operation(trap_box, "ltccTrapMinusHole - ltccBottomBox").publish(configuration)

    big_box = component_volume("ltcc_big_box")
    big_box.description = "Light Threshold Cerenkov Counter Box at the origin"
    big_box.solid = "G4Box"
    big_box.parameters = "3*m, 5*m, 6*m"
    big_box.publish(configuration)

    for sector in SECTORS:
        if not presence[sector - 1]:
            continue
        # this does not include the 5 cm shift for the forward carriage we observed
        c6toc12z = 1973
        rot_phi = 90 - (sector - 1) * 60
        sector_volume = new_volume(f"ltccS{sector}")
        sector_volume.description = f"ltcc sector {sector}"
        sector_volume.position = f"0*mm, 0*mm, {c6toc12z}*mm"
        sector_volume.rotations = [f"0*deg, 0*deg, {rot_phi}*deg"]
        sector_volume.color = "110088"
        sector_volume.visible = 0
        sector_volume.material = gas[sector - 1]
        operation(sector_volume, "ltcc_big_box * trapBox").publish(configuration)


