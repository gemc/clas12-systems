"""LTCC native-volume geometry, ported from clas12Tags geometry_source/ltcc.

Ported perl scripts: ltccBox.pl (sector boolean mother), cyl_mirrors.pl,
hyp_mirrors.pl, ell_mirrors.pl, pmts.pl, shields.pl. All shape parameters come
from `ltcc__parameters_default.txt`, generated by `root -q -b mirrors.C`
(see ltcc_parameters.py).

Not ported yet (they reference CAD meshes through `CopyOf` volumes and will be
added with the mesh import): ltcc_frame.pl and cones.pl. The ltcc_AlMgF2 optical
surface (mirrors.pl) is recorded on each mirror volume through `GVolume.mirror`;
its reflectivity table will be published when GEMC3 supports mirror surfaces.

Numeric values computed in perl are formatted with perl's default `%.15g`
stringification (`fstr`) so the output matches the clas12Tags references exactly;
values read from the parameters file are passed through as raw strings, as the
perl scripts interpolate them verbatim.
"""

import math

from pygemc import GVolume

from ltcc_parameters import load_parameters


NMIRRORS = 18  # mirrors per sector side; also the "nmirrors" parameter
SECTORS = (1, 2, 3, 4, 5, 6)

# sectors 1..6 presence and gas material per configuration (from ltcc.pl)
SECTOR_CONFIG = {
    "default": ((1, 1, 1, 1, 1, 1), ("C4F10",) * 6),
    "rga_spring2018": ((0, 1, 1, 0, 1, 1), ("na", "N2", "N2", "na", "C4F10", "N2")),
    "rga_fall2018": ((0, 0, 1, 0, 1, 0), ("na", "na", "C4F10", "na", "N2", "na")),
    "rgb_spring2019": ((0, 0, 1, 0, 1, 0), ("na", "na", "C4F10", "na", "C4F10", "na")),
    "rgb_spring2020": ((0, 0, 1, 0, 1, 0), ("na", "na", "C4F10", "na", "C4F10", "na")),
    "rgm_fall2021_H": ((0, 1, 1, 0, 1, 1), ("na", "N2", "N2", "na", "N2", "N2")),
}

MIRROR_SURFACE = "ltcc_AlMgF2"


def fstr(value):
    """Format a float the way perl stringifies numbers (%.15g)."""
    formatted = f"{float(value):.15g}"
    return "0" if formatted == "-0" else formatted


def perl_deg(value):
    """math.pm deg(): value*180.0/pi with the same operation order as perl."""
    return value * 180.0 / math.pi


def new_volume(name, mother="root"):
    volume = GVolume(name)
    volume.mother = mother
    volume.g4placement_type = "passive"
    return volume


def component_volume(name, mother="root"):
    volume = new_volume(name, mother)
    volume.material = "Component"
    return volume


def operation(volume, opr, parameters="0"):
    """Mark volume as the GEMC2 `Operation: a - b` boolean of two components."""
    volume.solidsOpr = opr
    volume.parameters = parameters
    return volume


def build_ltcc(configuration):
    """Publish all LTCC native volumes for the variation selected in configuration."""
    variation = configuration.variation
    presence, gas = SECTOR_CONFIG[variation]
    pars = load_parameters()

    build_ltcc_box(configuration, presence, gas)
    build_cyl_mirrors(configuration, pars, presence)
    build_hyp_mirrors(configuration, pars, presence, gas)
    build_ell_mirrors(configuration, pars, presence, gas)
    build_pmts(configuration, pars, presence)
    build_shields(configuration, pars, presence)


