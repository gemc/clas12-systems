def build_cad_copies(configuration):
    """Publish frame and Winston-cone copyOf placements for every present sector."""
    presence, _ = SECTOR_CONFIG[configuration.variation]
    pars = load_parameters()

    build_frame_copies(configuration, presence)
    build_winston_cone_copies(configuration, pars, presence)


def build_frame_copies(configuration, presence):
    """Reuse each sector-3 frame/nose mesh at the same local placement in the other sectors."""
    for sector in SECTORS:
        if sector == 3 or not presence[sector - 1]:
            continue
        for source, (material, color, position, rotation) in CAD_FRAME_SOURCES.items():
            frame = new_volume(f"{source}_s{sector}", f"ltccS{sector}")
            frame.description = f"LTCC sector {sector} {source} CAD copy"
            frame.position = position
            frame.rotations = [rotation]
            frame.material = material
            frame.color = color
            frame.copyOf = source
            frame.publish(configuration)


def build_winston_cone_copies(configuration, pars, presence):
    """Port cones.pl placements while reusing the three small/medium/large CAD meshes."""
    for n in range(1, NMIRRORS):  # clas12Tags omits cone segment 18
        if n < 11:
            source = "WC_S"
            material = "G4_Cu"
        elif n < 13:
            source = "WC_M"
            material = "G4_PLASTIC_SC_VINYLTOLUENE"
        else:
            source = "WC_L"
            material = "G4_Cu"

        segtheta = 90 - float(pars[f"ltcc.s{n}_theta"])
        segphi = fstr(90 - segtheta)
        tilt = pars[f"ltcc.wc.s{n}_angle"]
        shield_tilt = pars[f"ltcc.shield.s{n}_zangle"]

        for sector in SECTORS:
            if not presence[sector - 1]:
                continue
            for side, suffix, tilt_sign, shield_sign in (
                ("right", "R", "-", ""),
                ("left", "L", "", "-"),
            ):
                if (sector, side, n) in WINSTON_SOURCE_PLACEMENTS:
                    continue

                cone = new_volume(f"cone_s{sector}{side}_{n}", f"ltccS{sector}")
                cone.description = f"cone {side} {n}"
                cone.position = (
                    f"{pars[f'ltcc.wc.s{n}_x{suffix}']}*cm, "
                    f"{pars[f'ltcc.wc.s{n}_y{suffix}']}*cm, "
                    f"{pars[f'ltcc.wc.s{n}_z{suffix}']}*cm"
                )
                cone.rotations = [
                    f"{segphi}*deg, {tilt_sign}{tilt}*deg, {shield_sign}{shield_tilt}*deg"
                ]
                cone.material = material
                cone.color = "aa9999"
                cone.copyOf = source
                cone.mirror = MIRROR_SURFACE
                cone.publish(configuration)
