# cyl_mirrors.pl — cylindrical mirrors in front of the Winston cones
# ---------------------------------------------------------------------------
def build_cyl_mirrors(configuration, pars, presence):
    for n in range(1, NMIRRORS):  # perl: if ($n < $endN)
        s = n  # parameters are indexed by segment
        router = pars[f"ltcc.cyl.s{s}_router"]
        cyl_inner = fstr(float(router) - 0.1)  # mirror thickness is 1 mm
        cyl_ang = fstr(90 + float(pars[f"ltcc.shield.s{s}_zangle"]))
        segtheta = 90 - float(pars[f"ltcc.s{s}_theta"])
        segphi_cyl = fstr(-90 - segtheta)
        tilt = pars[f"ltcc.wc.s{s}_angle"]

        for sector in SECTORS:
            if not presence[sector - 1]:
                continue
            # unlike the pmts, the left cylindrical mirror carries the -tilt
            for side, tilt_sign in (("right", ""), ("left", "-")):
                mirror = new_volume(f"cyl_mirrors_s{sector}{side}_{n}", f"ltccS{sector}")
                mirror.description = f"cyl mirrors {side} {n}"
                suffix = "R" if side == "right" else "L"
                mirror.position = (
                    f"{pars[f'ltcc.mirror.s{s}_x{suffix}']}*cm, "
                    f"{pars[f'ltcc.mirror.s{s}_y{suffix}']}*cm, "
                    f"{pars[f'ltcc.mirror.s{s}_z{suffix}']}*cm"
                )
                mirror_tilt = tilt_sign + tilt
                cyl_tilt = pars[f"ltcc.cyl.s{s}_{'rightAngle' if side == 'right' else 'leftAngle'}"]
                mirror.rotations = [f"{segphi_cyl}*deg, {mirror_tilt}*deg, {cyl_tilt}*deg"]
                mirror.color = "aaffff"
                mirror.solid = "G4Tubs"
                mirror.parameters = f"{cyl_inner}*cm, {router}*cm, 3*cm, 0*deg, {cyl_ang}*deg"
                mirror.material = "G4_Al"
                mirror.style = 1
                mirror.mirror = MIRROR_SURFACE
                mirror.publish(configuration)


