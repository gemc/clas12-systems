from pygemc import GVolume

from ltcc_parameters import load_parameters


NMIRRORS = 18  # mirrors per sector side; also the "nmirrors" parameter
SECTORS = (1, 2, 3, 4, 5, 6)

# All six sector gas mothers are identical (see build_ltcc_box). The CAD meshes are sourced from sector 3
# and reused in the other sectors with copyOf placements; the shared mother is sized to contain them.

