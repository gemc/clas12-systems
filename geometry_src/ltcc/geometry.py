def fstr(value):
    """Format a float the way perl stringifies numbers (%.15g)."""
    formatted = f"{float(value):.15g}"
    return "0" if formatted == "-0" else formatted


def perl_deg(value):
    """math.pm deg(): value*180.0/pi with the same operation order as perl."""
    return value * 180.0 / math.pi


def new_volume(name, mother="root"):
    volume = GVolume(name)
    volume.mother = mother
    volume.g4placement_type = "passive"
    return volume


def component_volume(name, mother="root"):
    volume = new_volume(name, mother)
    volume.material = "Component"
    return volume


def operation(volume, opr, parameters="0"):
    """Mark volume as the GEMC2 `Operation: a - b` boolean of two components."""
    volume.solidsOpr = opr
    volume.parameters = parameters
    return volume


def build_ltcc(configuration):
    """Publish all LTCC native volumes for the variation selected in configuration."""
    variation = configuration.variation
    presence, gas = SECTOR_CONFIG[variation]
    pars = load_parameters()

    build_ltcc_box(configuration, presence, gas)
    build_cyl_mirrors(configuration, pars, presence)
    build_hyp_mirrors(configuration, pars, presence, gas)
    build_ell_mirrors(configuration, pars, presence, gas)
    build_pmts(configuration, pars, presence)
    build_shields(configuration, pars, presence)


# ---------------------------------------------------------------------------
# ltccBox.pl — sector gas mother, one identical G4Trap wedge per sector
# ---------------------------------------------------------------------------
# GEMC2 placed a tilted G4Trap inside each unrotated sector mother by intersecting it with a large box.
# Keep that boolean-placement idiom so the existing daughter coordinates remain in the sector frame, but
# fit the trap to the native and CAD content rather than the larger DC-to-PCAL envelope.
def build_ltcc_box(configuration, presence, gas):
    # Coordinates are in the sector frame: x is azimuthal, y radial and z along the beam. The asymmetric
    # y half-lengths closely follow the LTCC outline, while 680 mm of normal half-depth contains the final
    # native mirror segments and the sector-3 CAD frame. The x dimensions are derived from a 29.9 deg
    # sector half-angle; deriving all four together keeps the G4Trap side faces exactly planar.
    half_z = 680.0
    half_y_minus_z = 1930.0
    half_y_plus_z = 1500.0
    center_y = 1800.0
    center_z = 3900.0
    tilt = 25.0
    sector_half_angle = 29.9

    tilt_rad = math.radians(tilt)
    sector_half_angle_rad = math.radians(sector_half_angle)
    wedge_tangent = math.tan(sector_half_angle_rad)
    side_slope = math.cos(tilt_rad) * wedge_tangent
    radial_minus_z = center_y + math.sin(tilt_rad) * half_z
    radial_plus_z = center_y - math.sin(tilt_rad) * half_z
    dx1 = radial_minus_z * wedge_tangent - half_y_minus_z * side_slope
    dx2 = radial_minus_z * wedge_tangent + half_y_minus_z * side_slope
    dx3 = radial_plus_z * wedge_tangent - half_y_plus_z * side_slope
    dx4 = radial_plus_z * wedge_tangent + half_y_plus_z * side_slope

    trap = component_volume("ltccTrap")
    trap.description = "Light Threshold Cerenkov Counter sector"
    trap.color = "110088"
    trap.solid = "G4Trap"
    trap.parameters = (
        f"{fstr(half_z)}*mm, 0*deg, 0*deg, {fstr(half_y_minus_z)}*mm, "
        f"{fstr(dx1)}*mm, {fstr(dx2)}*mm, 0*deg, {fstr(half_y_plus_z)}*mm, "
        f"{fstr(dx3)}*mm, {fstr(dx4)}*mm, 0*deg"
    )
    trap.position = f"0*mm, {fstr(center_y)}*mm, {fstr(center_z)}*mm"
    trap.rotations = [f"{fstr(tilt)}*deg, 180*deg, 0*deg"]
    trap.publish(configuration)

    big_box = component_volume("ltcc_big_box")
    big_box.description = "Light Threshold Cerenkov Counter Box at the origin"
    big_box.solid = "G4Box"
    big_box.parameters = "3*m, 5*m, 6*m"
    big_box.publish(configuration)

    for sector in SECTORS:
        if not presence[sector - 1]:
            continue
        # this does not include the 5 cm shift for the forward carriage we observed
        c6toc12z = 1973
        rot_phi = 90 - (sector - 1) * 60
        sector_volume = new_volume(f"ltccS{sector}")
        sector_volume.description = f"ltcc sector {sector}"
        sector_volume.position = f"0*mm, 0*mm, {c6toc12z}*mm"
        sector_volume.rotations = [f"0*deg, 0*deg, {rot_phi}*deg"]
        sector_volume.color = "110088"
        sector_volume.visible = 0
        sector_volume.material = gas[sector - 1]
        operation(sector_volume, "ltcc_big_box * ltccTrap").publish(configuration)


