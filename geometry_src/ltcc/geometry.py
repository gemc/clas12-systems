"""LTCC native-volume geometry, ported from clas12Tags geometry_source/ltcc.

Ported perl scripts: ltccBox.pl (sector boolean mother), cyl_mirrors.pl,
hyp_mirrors.pl, ell_mirrors.pl, pmts.pl, shields.pl. All shape parameters come
from `ltcc__parameters_default.txt`, generated by `root -q -b mirrors.C`
(see ltcc_parameters.py).

The CAD mesh sources are rows in the same `ltcc` SQLite system as the native
geometry. Their placement is authored in `stls/cad__default.yaml` and uploaded
by the gcad feature (see ltcc.py); the remaining frame and Winston-cone
placements are generated here as `copyOf` volumes. The STL meshes are built by
`build_cad_meshes.py`. The ltcc_AlMgF2 optical surface (mirrors.pl) is recorded
on every native mirror and source/copied Winston cone through `GVolume.mirror`.

Numeric values computed in perl are formatted with perl's default `%.15g`
stringification (`fstr`) so the output matches the clas12Tags references exactly;
values read from the parameters file are passed through as raw strings, as the
perl scripts interpolate them verbatim.
"""

